// يبني مسار أي ملف ثابت (مثل صورة الشعار) مع إضافة بادئة المسار الأساسي،
// عشان تظهر الصورة بشكل صحيح سواء نُشر الموقع على الجذر (فيرسل) أو تحت
// مسار فرعي مثل ‎/form-preview‎ على خادم المعاينة. بدون هذي البادئة تعطي
// الصورة خطأ 404 تحت المسار الفرعي.

const basePath = process.env.NEXT_PUBLIC_BASE_PATH || '';

export function assetUrl(path) {
  return `${basePath}${path}`;
}
